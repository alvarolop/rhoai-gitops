#!/bin/bash
# Generates, for every MaaS tenant namespace, ONE MaaSSubscription and ONE MaaSAuthPolicy that cover all the MaaSModelRefs
# of the namespace with the same default token limit. Rerun it after deploying (or deleting) a model: the same two resources
# are updated (oc apply), so the new model joins the subscription and a deleted one leaves it.
#
#   ./maas-subscriptions.sh                          # all tenants (AITenant), defaults below
#   ./maas-subscriptions.sh models-as-a-service      # only these namespaces
#   ./maas-subscriptions.sh --dry-run                # print the manifests, apply nothing
#   LIMIT=50000 WINDOW=1m GROUPS_LIST=cluster-admins,team-a ./maas-subscriptions.sh
#
# Variables: NAME (default all-models), LIMIT (100000), WINDOW (1h), GROUPS_LIST (system:authenticated, comma separated),
# PRIORITY (0), EXCLUDE (comma separated MaaSModelRef names that keep their own subscription, e.g. the demo simulator).
# The subscription of a namespace lives in that namespace: each tenant has its own maas-api and gateway, so a subscription
# cannot cover models of two tenants. The groups of a Keycloak tenant are the ones of its token (groups claim).
# These resources are not in git: the Argo CD applications use prune: false, so they are left alone.

set -euo pipefail

DRY_RUN=false; NAMESPACES=()
for a in "$@"; do [[ "$a" == "--dry-run" ]] && DRY_RUN=true || NAMESPACES+=("$a"); done

NAME="${NAME:-all-models}"
LIMIT="${LIMIT:-100000}"
WINDOW="${WINDOW:-1h}"
GROUPS_LIST="${GROUPS_LIST:-system:authenticated}"
PRIORITY="${PRIORITY:-0}"
EXCLUDE="${EXCLUDE:-}"

oc whoami &> /dev/null || { echo "❌ You are not logged in. Please log in and run the script again." >&2; exit 1; }

if [[ ${#NAMESPACES[@]} -eq 0 ]]; then
    mapfile -t NAMESPACES < <(oc get aitenant -A -o json | jq -r '.items[] | .status.tenantNamespace // empty')
fi
[[ ${#NAMESPACES[@]} -gt 0 ]] || { echo "❌ No tenant namespace found (no AITenant). Pass the namespaces as arguments." >&2; exit 1; }

for NS in "${NAMESPACES[@]}"; do
    MODELS=$(oc get maasmodelref -n "$NS" -o json | jq -c --arg ex "$EXCLUDE" \
        '[.items[].metadata.name] | map(select(. as $n | ($ex | split(",") | index($n)) | not)) | sort')
    if [[ "$MODELS" == "[]" ]]; then echo "⏭️  $NS: no MaaSModelRef, nothing to do" >&2; continue; fi

    MANIFEST=$(jq -n --arg ns "$NS" --arg name "$NAME" --arg limit "$LIMIT" --arg window "$WINDOW" --arg prio "$PRIORITY" \
        --arg groups "$GROUPS_LIST" --argjson models "$MODELS" '
        ($groups | split(",") | map({name: .})) as $g
        | {apiVersion: "v1", kind: "List", items: [
            {apiVersion: "maas.opendatahub.io/v1alpha1", kind: "MaaSSubscription",
             metadata: {name: $name, namespace: $ns,
                        annotations: {"openshift.io/display-name": "All models of \($ns)",
                                      "openshift.io/description": "Generated by maas-subscriptions.sh: every MaaSModelRef of the namespace"}},
             spec: {modelRefs: ($models | map({name: ., namespace: $ns, tokenRateLimits: [{limit: ($limit|tonumber), window: $window}]})),
                    owner: {groups: $g}, priority: ($prio|tonumber)}},
            {apiVersion: "maas.opendatahub.io/v1alpha1", kind: "MaaSAuthPolicy",
             metadata: {name: "\($name)-policy", namespace: $ns,
                        annotations: {"openshift.io/description": "Generated by maas-subscriptions.sh"}},
             spec: {modelRefs: ($models | map({name: ., namespace: $ns})), subjects: {groups: $g}}}]}')

    if $DRY_RUN; then
        echo "# $NS: $(jq -r 'join(", ")' <<< "$MODELS")" >&2
        oc apply --dry-run=server -f - <<< "$MANIFEST"
    else
        oc apply -f - <<< "$MANIFEST" >/dev/null
        echo "✅ $NS: $NAME + $NAME-policy cover $(jq -r 'length' <<< "$MODELS") model(s): $(jq -r 'join(", ")' <<< "$MODELS")" >&2
    fi
done
